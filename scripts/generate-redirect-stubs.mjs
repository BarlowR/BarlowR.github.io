/**
 * One-shot generator for the redirect stubs that keep old Jekyll URLs alive.
 *
 * Jekyll rendered every content page at its in-repo path
 * (`/content/trips/<dir>/<Name>.html`); the Astro port serves the same pages
 * at clean URLs (`/trips/<dir>/`). External backlinks and search results still
 * point at the old `.html` addresses, so this script writes a meta-refresh
 * stub (same shape as the old `_layouts/redirect.html`, cf. `public/info.html`)
 * into `public/` for every page that was published on the Jekyll site.
 *
 * The stubs land under `public/content/…`, which never collides with
 * `src/lib/mirror-static.ts`: the mirror only carries non-markdown files, and
 * no real file in `content/` shares a name with a stub.
 *
 * Run from the repo root: `node scripts/generate-redirect-stubs.mjs`
 */
import fs from 'node:fs';
import path from 'node:path';
import {
  galleryUrl,
  postUrl,
  projectUrl,
  tripUrl,
} from '../src/lib/slug.ts';

const root = process.cwd();

const URL_BY_COLLECTION = {
  trips: tripUrl,
  projects: projectUrl,
  posts: postUrl,
  gallery: galleryUrl,
};

/** Minimal front-matter probe: was this page published on the Jekyll site? */
function isPublished(file) {
  const text = fs.readFileSync(file, 'utf8');
  const match = text.match(/^---\n([\s\S]*?)\n---/);
  return !/^published:\s*false\s*$/m.test(match ? match[1] : '');
}

function* markdownFiles(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* markdownFiles(full);
    else if (entry.name.endsWith('.md')) yield full;
  }
}

function stub(target) {
  return `<!-- Redirect stub for an old Jekyll URL; generated by scripts/generate-redirect-stubs.mjs -->
<!DOCTYPE html>
<html>
<head>
    <meta charset="utf-8"/>
    <meta http-equiv="refresh" content="0;url=${target}"/>
    <link rel="canonical" href="https://barlowr.com${target}"/>
    <script type="text/javascript">
        window.location.href = "${target}";
    </script>
    <title>Page Redirection</title>
</head>
<body>
    If you are not redirected automatically, follow <a href='${target}'>this link</a>.
</body>
</html>
`;
}

const redirects = [['books.html', '/books/']];

for (const [collection, toUrl] of Object.entries(URL_BY_COLLECTION)) {
  const base = path.join(root, 'content', collection);
  for (const file of markdownFiles(base)) {
    if (!isPublished(file)) continue;
    const id = path.relative(base, file).replace(/\.md$/, '');
    const oldPath = path.join('content', collection, `${id}.html`);
    redirects.push([oldPath, toUrl(id)]);
  }
}

for (const [oldPath, target] of redirects) {
  const outFile = path.join(root, 'public', oldPath);
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, stub(target));
  console.log(`${oldPath} -> ${target}`);
}
console.log(`${redirects.length} redirect stubs written to public/`);
